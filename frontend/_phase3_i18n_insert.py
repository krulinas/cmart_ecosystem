def insert(path: Path, staff: str, organizer: str) -> None:
    text = path.read_text(encoding="utf-8")
    marker = "  },\n};"
    idx = text.rfind(marker)
    if idx < 0:
        raise SystemExit(f"marker not found in {path}")
    before = text[:idx]
    # Restore insights close, then staff (ends with comma) + organizer (no trailing comma).
    org = organizer.strip().rstrip().rstrip(",")
    new = before + "  },\n" + staff.strip() + "\n" + org + ",\n};\n"
    path.write_text(new, encoding="utf-8")
    print(f"Updated {path}")


